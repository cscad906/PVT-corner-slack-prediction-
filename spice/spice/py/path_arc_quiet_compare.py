#!/usr/bin/env python3.11
"""Prepare and summarize per-path arc aligned-aggressor HSPICE runs.

This utility supports two steps:

1. prepare-stage-csv
   Build a compact stage list for PT write_spice_deck from
   pt_si_stage_compact.csv and a PT timing report. The timing report is used
   only to recover the receiver transition direction, which selects max_rise
   or max_fall for each net arc.

2. prepare-stage-csv-from-report
   Build the same stage list directly from one PT SI-on timing report.

3. run-quiet-compare
   For each stage deck generated by run_pt_aligned_path_arcs_spice_deck.tcl,
   run the aligned deck, create a quiet copy by moving all sweep shifts far
   away, run that deck, and compare stage delay on the same arc deck.
"""

from __future__ import annotations

import argparse
import csv
import math
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Iterable


FLOAT_RE = re.compile(r"^[+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?$")
PIN_LINE_RE = re.compile(r"^\s*(\S+)\s+\([^)]*\).*?\s([rf])\s*$")
STAGE_CSV_FIELDS = [
    "stage_idx",
    "analysis_type",
    "direction",
    "cell_from",
    "cell_to",
    "net_from",
    "net_to",
    "stage_from",
    "stage_to",
    "pt_si_cell_ps",
    "pt_si_net_ps",
    "pt_si_stage_ps",
    "in_slew_ps",
    "out_slew_ps",
    "victim_net",
]


def pin_measure_token(pin: str) -> str:
    return pin.strip().lower()


def measure_name(pin_from: str, pin_to: str) -> str:
    return f"delay_{pin_measure_token(pin_from)}_{pin_measure_token(pin_to)}"


def pin_from_measure_source(measure: str, dst_pin: str) -> str | None:
    dst = "_" + pin_measure_token(dst_pin)
    if not measure.startswith("delay_") or not measure.endswith(dst):
        return None
    return measure[len("delay_") : -len(dst)]


def parse_direction_map(si_rpt: Path) -> dict[str, str]:
    directions: dict[str, str] = {}
    with si_rpt.open() as f:
        for line in f:
            m = PIN_LINE_RE.match(line)
            if not m:
                continue
            pin, direction = m.group(1), m.group(2)
            directions[pin] = direction
    return directions


def infer_victim_net(net_from: str) -> str:
    if "/" not in net_from:
        return ""
    inst, pin = net_from.rsplit("/", 1)
    return ""


def write_stage_csv(path: Path, rows: list[dict[str, object]]) -> None:
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=STAGE_CSV_FIELDS)
        writer.writeheader()
        writer.writerows(rows)


def prepare_stage_csv(args: argparse.Namespace) -> None:
    directions = parse_direction_map(args.si_rpt)
    args.out_dir.mkdir(parents=True, exist_ok=True)

    out_csv = args.out_dir / args.output_name
    missing_dirs: list[tuple[int, str]] = []
    rows_out: list[dict[str, str]] = []

    with args.pt_stage_csv.open(newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            if args.path_id is not None and int(row["path_id"]) != args.path_id:
                continue
            if args.limit and len(rows_out) >= args.limit:
                break
            stage_idx = int(row["stage_idx"])
            net_to = row["net_to"]
            direction = directions.get(net_to, "")
            if direction not in {"r", "f"}:
                missing_dirs.append((stage_idx, net_to))
                direction = "r"
            analysis_type = "max_rise" if direction == "r" else "max_fall"
            victim_net = row.get("net_name", "").strip()
            if not victim_net:
                # pt_si_stage_compact.csv may not carry the net name, but the
                # PT report puts it on the net row immediately before net_to.
                victim_net = ""
            rows_out.append(
                {
                    "stage_idx": str(stage_idx),
                    "analysis_type": analysis_type,
                    "direction": direction,
                    "cell_from": row["cell_from"],
                    "cell_to": row["cell_to"],
                    "net_from": row["net_from"],
                    "net_to": row["net_to"],
                    "stage_from": row["stage_from"],
                    "stage_to": row["stage_to"],
                    "pt_si_cell_ps": row["cell_ps"],
                    "pt_si_net_ps": row["net_ps"],
                    "pt_si_stage_ps": row["stage_ps"],
                    "in_slew_ps": row.get("in_slew_ps", ""),
                    "out_slew_ps": row.get("out_slew_ps", ""),
                    "victim_net": victim_net,
                }
            )

    if any(not r["victim_net"] for r in rows_out):
        fill_victim_nets(args.si_rpt, rows_out)

    write_stage_csv(out_csv, rows_out)

    print(f"Wrote {out_csv}")
    print(f"stage_rows={len(rows_out)}")
    if missing_dirs:
        print(f"WARNING: missing receiver directions for {len(missing_dirs)} stages; defaulted to max_rise")
        for stage_idx, pin in missing_dirs[:10]:
            print(f"  stage {stage_idx}: {pin}")


def prepare_stage_csv_from_report(args: argparse.Namespace) -> None:
    native_flow_dir = Path(__file__).resolve().parents[1] / "native_flow"
    sys.path.insert(0, str(native_flow_dir))
    from format_pt_si_report import build_stages, parse_pt_report

    args.out_dir.mkdir(parents=True, exist_ok=True)
    parsed = parse_pt_report(args.si_rpt)
    parsed_rows, _summary = build_stages(parsed, {"status": "PASS"}, args.path_id, args.out_dir)
    directions = parse_direction_map(args.si_rpt)
    rows_out: list[dict[str, object]] = []
    missing_dirs: list[tuple[int, str]] = []

    for row in parsed_rows:
        net_to = str(row["net_to"])
        direction = directions.get(net_to, "")
        if direction not in {"r", "f"}:
            missing_dirs.append((int(row["stage_idx"]), net_to))
            direction = "r"
        rows_out.append(
            {
                "stage_idx": row["stage_idx"],
                "analysis_type": "max_rise" if direction == "r" else "max_fall",
                "direction": direction,
                "cell_from": row["cell_from"],
                "cell_to": row["cell_to"],
                "net_from": row["net_from"],
                "net_to": net_to,
                "stage_from": row["stage_from"],
                "stage_to": row["stage_to"],
                "pt_si_cell_ps": row["cell_ps"],
                "pt_si_net_ps": row["net_ps"],
                "pt_si_stage_ps": row["stage_ps"],
                "in_slew_ps": row.get("in_slew_ps", ""),
                "out_slew_ps": row.get("out_slew_ps", ""),
                "victim_net": "",
            }
        )

    fill_victim_nets(args.si_rpt, rows_out)
    out_csv = args.out_dir / args.output_name
    write_stage_csv(out_csv, rows_out)
    print(f"Wrote {out_csv}")
    print(f"stage_rows={len(rows_out)}")
    if missing_dirs:
        print(f"WARNING: missing receiver directions for {len(missing_dirs)} stages; defaulted to max_rise")


def fill_victim_nets(si_rpt: Path, rows: list[dict[str, str]]) -> None:
    wanted = {row["net_to"]: row for row in rows}
    last_net = ""
    net_re = re.compile(r"^\s*(\S+)\s+\(net\)\s+")
    pin_re = re.compile(r"^\s*(\S+)\s+\([^)]*\)")
    with si_rpt.open() as f:
        for line in f:
            net_m = net_re.match(line)
            if net_m:
                last_net = net_m.group(1)
                continue
            pin_m = pin_re.match(line)
            if not pin_m:
                continue
            pin = pin_m.group(1)
            row = wanted.get(pin)
            if row and not row["victim_net"]:
                row["victim_net"] = last_net


def is_number_token(token: str) -> bool:
    return bool(FLOAT_RE.match(token))


def parse_num(token: str) -> float:
    token = token.strip()
    if token.lower().endswith("ns"):
        token = token[:-2]
    return float(token)


def parse_mt0(path: Path) -> tuple[list[str], list[dict[str, float]]]:
    header: list[str] = []
    data_tokens: list[str] = []
    data_started = False

    with path.open(errors="ignore") as f:
        for raw in f:
            line = raw.strip()
            if not line:
                continue
            if line.startswith("$") or line.upper().startswith(".TITLE"):
                continue
            tokens = line.split()
            if not tokens:
                continue
            starts_numeric = is_number_token(tokens[0])
            if not data_started and starts_numeric:
                data_started = True
            if data_started:
                data_tokens.extend(tokens)
            else:
                header.extend(tokens)

    if not header:
        raise ValueError(f"no mt0 header in {path}")
    if not data_tokens:
        raise ValueError(f"no mt0 data in {path}")

    row_len = len(header)
    rows: list[dict[str, float]] = []
    pos = 0
    while pos + row_len <= len(data_tokens):
        chunk = data_tokens[pos : pos + row_len]
        pos += row_len
        row: dict[str, float] = {}
        for name, token in zip(header, chunk):
            try:
                row[name.lower()] = parse_num(token)
            except ValueError:
                row[name.lower()] = math.nan
        rows.append(row)
    if not rows:
        raise ValueError(f"could not assemble mt0 rows from {path}")
    return [h.lower() for h in header], rows


def run_cmd(cmd: list[str], cwd: Path, log: Path | None = None) -> None:
    print(f"RUN: {' '.join(cmd)}  (cwd={cwd})", flush=True)
    with (log.open("w") if log else subprocess.DEVNULL) as stdout:
        proc = subprocess.run(
            cmd,
            cwd=str(cwd),
            stdout=stdout,
            stderr=subprocess.STDOUT if log else subprocess.DEVNULL,
            text=True,
        )
    if proc.returncode != 0:
        raise RuntimeError(f"command failed rc={proc.returncode}: {' '.join(cmd)}")


def find_sweep_file(stage_dir: Path, deck_basename: str) -> Path | None:
    cand = stage_dir / f"{deck_basename}_sweep.sp"
    if cand.exists():
        return cand
    matches = sorted(stage_dir.glob("*_sweep.sp"))
    return matches[0] if matches else None


def collect_sweep_header(path: Path) -> list[str]:
    text = path.read_text(errors="ignore").splitlines()
    in_data = False
    names: list[str] = []
    for line in text:
        stripped = line.strip()
        if not in_data:
            if stripped.lower().startswith(".data"):
                in_data = True
                names.extend(stripped.split()[2:])
            continue
        if stripped.lower().startswith(".enddata"):
            break
        tokens = stripped.lstrip("+").split()
        if not tokens:
            continue
        if all(tok.lower().startswith("shift") for tok in tokens):
            names.extend(tokens)
            continue
        break
    return names


def write_quiet_sweep(path: Path, shift_names: list[str]) -> None:
    with path.open("w") as f:
        f.write(".data sweep_data")
        for idx, name in enumerate(shift_names):
            if idx % 8 == 0:
                f.write("\n+")
            f.write(f" {name}")
        f.write("\n+")
        for idx, _name in enumerate(shift_names):
            if idx and idx % 8 == 0:
                f.write("\n+")
            f.write(" 1000ns")
        f.write("\n.enddata\n")


def copy_quiet_deck(stage_dir: Path, deck_basename: str) -> tuple[Path, Path | None]:
    quiet_dir = stage_dir / "quiet"
    existing_mt0 = quiet_dir / "quietbase.mt0"
    if quiet_dir.exists() and existing_mt0.exists():
        return quiet_dir, find_sweep_file(quiet_dir, deck_basename)
    if quiet_dir.exists():
        shutil.rmtree(quiet_dir)
    quiet_dir.mkdir()
    for path in stage_dir.glob("*.sp"):
        if path.is_file():
            shutil.copy2(path, quiet_dir / path.name)
    sweep = find_sweep_file(quiet_dir, deck_basename)
    if sweep:
        shift_names = collect_sweep_header(sweep)
        if shift_names:
            write_quiet_sweep(sweep, shift_names)
    return quiet_dir, sweep


def hspice_outputs(prefix: Path) -> list[Path]:
    return [prefix.with_suffix(".mt0"), prefix.with_suffix(".lis"), prefix.with_suffix(".st0")]


def measure_value(headers: list[str], rows: list[dict[str, float]], name: str) -> float | None:
    key = name.lower()
    if key not in headers:
        return None
    values = [row.get(key, math.nan) for row in rows]
    valid = [v for v in values if not math.isnan(v) and abs(v) < 9.0e29]
    if not valid:
        return None
    return valid[0] * 1.0e12


def max_measure_value(headers: list[str], rows: list[dict[str, float]], name: str) -> float | None:
    key = name.lower()
    if key not in headers:
        return None
    values = [row.get(key, math.nan) for row in rows]
    valid = [v for v in values if not math.isnan(v) and abs(v) < 9.0e29]
    if not valid:
        return None
    return max(valid) * 1.0e12


def measure_from_row(headers: list[str], row: dict[str, float] | None, name: str) -> float | None:
    key = name.lower()
    if row is None or key not in headers:
        return None
    value = row.get(key, math.nan)
    if math.isnan(value) or abs(value) >= 9.0e29:
        return None
    return value * 1.0e12


def max_measure_row(
    headers: list[str], rows: list[dict[str, float]], name: str
) -> dict[str, float] | None:
    key = name.lower()
    if key not in headers:
        return None
    valid_rows = [
        row
        for row in rows
        if not math.isnan(row.get(key, math.nan)) and abs(row.get(key, math.nan)) < 9.0e29
    ]
    if not valid_rows:
        return None
    return max(valid_rows, key=lambda row: row[key])


def center_measure_value(headers: list[str], rows: list[dict[str, float]], name: str) -> float | None:
    key = name.lower()
    if key not in headers:
        return None
    shift_cols = [h for h in headers if h.startswith("shift")]
    if not shift_cols:
        return measure_value(headers, rows, name)
    best_row = None
    best_score = None
    for row in rows:
        score = sum(abs(row.get(col, 0.0)) for col in shift_cols)
        if best_score is None or score < best_score:
            best_score = score
            best_row = row
    if best_row is None:
        return None
    value = best_row.get(key, math.nan)
    if math.isnan(value) or abs(value) >= 9.0e29:
        return None
    return value * 1.0e12


def choose_stage_measure(
    headers: list[str],
    preferred: str,
    stage_to: str,
    net_from: str,
) -> tuple[str, str, str]:
    preferred = preferred.lower()
    if preferred in headers:
        return preferred, "exact_path_stage", ""
    dst = pin_measure_token(stage_to)
    net_only = measure_name(net_from, stage_to).lower()
    candidates = [h for h in headers if h.startswith("delay_") and h.endswith("_" + dst)]
    non_net = [h for h in candidates if h != net_only]
    if non_net:
        chosen = sorted(non_net, key=len)[0]
        return chosen, "pt_selected_stage_source", pin_from_measure_source(chosen, stage_to) or ""
    if candidates:
        chosen = sorted(candidates, key=len)[0]
        return chosen, "net_only_fallback", pin_from_measure_source(chosen, stage_to) or ""
    return preferred, "missing", ""


def parse_pt_delta(delay_rpt: Path, analysis_type: str) -> tuple[float | None, float | None, float | None]:
    if not delay_rpt.exists():
        return None, None, None
    text = delay_rpt.read_text(errors="ignore")

    def find(direction: str) -> float | None:
        m = re.search(
            rf"Annotated max {direction} net delta delay:\s*"
            rf"([+-]?(?:\d+(?:\.\d*)?|\.\d+)(?:[eE][+-]?\d+)?)",
            text,
        )
        if not m:
            return None
        return float(m.group(1)) * 1000.0

    rise = find("rise")
    fall = find("fall")
    selected = rise if analysis_type == "max_rise" else fall
    return selected, rise, fall


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def run_quiet_compare(args: argparse.Namespace) -> None:
    manifest = read_csv(args.manifest)
    stage_rows = {row["stage_idx"]: row for row in read_csv(args.stage_csv)}
    results: list[dict[str, object]] = []

    for rec in manifest:
        stage_idx = rec["stage_idx"]
        if rec.get("status") != "PASS":
            results.append({"stage_idx": stage_idx, "status": "PT_DECK_FAIL", "message": rec.get("message", "")})
            continue
        stage = stage_rows.get(stage_idx, {})
        stage_dir = Path(rec["stage_dir"])
        deck_basename = rec["deck_basename"]
        deck_file = stage_dir / f"{deck_basename}.sp"
        if not deck_file.exists():
            results.append({"stage_idx": stage_idx, "status": "DECK_MISSING", "message": str(deck_file)})
            continue

        aligned_prefix = stage_dir / f"{deck_basename}_hspice"
        aligned_mt0 = aligned_prefix.with_suffix(".mt0")
        try:
            if args.force or not aligned_mt0.exists():
                run_cmd([args.hspice, deck_file.name, "-o", aligned_prefix.name], stage_dir, stage_dir / "hspice_aligned.log")

            quiet_dir, _quiet_sweep = copy_quiet_deck(stage_dir, deck_basename)
            quiet_prefix = quiet_dir / "quietbase"
            quiet_mt0 = quiet_prefix.with_suffix(".mt0")
            if args.force or not quiet_mt0.exists():
                run_cmd([args.hspice, deck_file.name, "-o", quiet_prefix.name], quiet_dir, quiet_dir / "hspice_quiet.log")

            aligned_headers, aligned_rows = parse_mt0(aligned_mt0)
            quiet_headers, quiet_rows = parse_mt0(quiet_mt0)

            cell_measure = measure_name(stage.get("cell_from", rec["cell_from"]), stage.get("cell_to", rec["cell_to"]))
            net_measure = measure_name(stage.get("net_from", rec["net_from"]), stage.get("net_to", rec["net_to"]))
            preferred_stage_measure = measure_name(stage.get("stage_from", rec["stage_from"]), stage.get("stage_to", rec["stage_to"]))
            stage_measure, stage_measure_mode, selected_stage_source = choose_stage_measure(
                aligned_headers,
                preferred_stage_measure,
                stage.get("stage_to", rec["stage_to"]),
                stage.get("net_from", rec["net_from"]),
            )
            if stage_measure_mode == "pt_selected_stage_source" and selected_stage_source:
                cell_measure = measure_name(selected_stage_source, stage.get("cell_to", rec["cell_to"]))

            quiet_cell = measure_value(quiet_headers, quiet_rows, cell_measure)
            quiet_net = measure_value(quiet_headers, quiet_rows, net_measure)
            quiet_stage = measure_value(quiet_headers, quiet_rows, stage_measure)
            align_cell_center = center_measure_value(aligned_headers, aligned_rows, cell_measure)
            align_net_center = center_measure_value(aligned_headers, aligned_rows, net_measure)
            align_stage_center = center_measure_value(aligned_headers, aligned_rows, stage_measure)
            align_cell_worst = max_measure_value(aligned_headers, aligned_rows, cell_measure)
            align_net_worst = max_measure_value(aligned_headers, aligned_rows, net_measure)
            align_stage_worst = max_measure_value(aligned_headers, aligned_rows, stage_measure)
            stage_worst_row = max_measure_row(aligned_headers, aligned_rows, stage_measure)
            align_cell_at_stage_worst = measure_from_row(aligned_headers, stage_worst_row, cell_measure)
            align_net_at_stage_worst = measure_from_row(aligned_headers, stage_worst_row, net_measure)
            align_stage_at_stage_worst = measure_from_row(aligned_headers, stage_worst_row, stage_measure)

            pt_delta, pt_delta_rise, pt_delta_fall = parse_pt_delta(
                stage_dir / "arc_delay_calculation_crosstalk.rpt", rec["analysis_type"]
            )
            status = "PASS"
            message = ""
            if quiet_stage is None or align_stage_worst is None:
                status = "MEASURE_MISSING"
                message = stage_measure
            results.append(
                {
                    "stage_idx": int(stage_idx),
                    "status": status,
                    "message": message,
                    "analysis_type": rec["analysis_type"],
                    "direction": stage.get("direction", ""),
                    "victim_net": rec["victim_net"],
                    "cell_arc": f"{stage.get('cell_from', rec['cell_from'])} -> {stage.get('cell_to', rec['cell_to'])}",
                    "net_arc": f"{stage.get('net_from', rec['net_from'])} -> {stage.get('net_to', rec['net_to'])}",
                    "stage_arc": f"{stage.get('stage_from', rec['stage_from'])} -> {stage.get('stage_to', rec['stage_to'])}",
                    "pt_si_cell_ps": as_float(stage.get("pt_si_cell_ps")),
                    "pt_si_net_ps": as_float(stage.get("pt_si_net_ps")),
                    "pt_si_stage_ps": as_float(stage.get("pt_si_stage_ps")),
                    "pt_arc_delta_selected_ps": pt_delta,
                    "pt_arc_delta_rise_ps": pt_delta_rise,
                    "pt_arc_delta_fall_ps": pt_delta_fall,
                    "stage_measure_mode": stage_measure_mode,
                    "stage_measure": stage_measure,
                    "selected_stage_source": selected_stage_source,
                    "quiet_cell_ps": quiet_cell,
                    "quiet_net_ps": quiet_net,
                    "quiet_stage_ps": quiet_stage,
                    "align_cell_center_ps": align_cell_center,
                    "align_net_center_ps": align_net_center,
                    "align_stage_center_ps": align_stage_center,
                    "align_cell_worst_ps": align_cell_worst,
                    "align_net_worst_ps": align_net_worst,
                    "align_stage_worst_ps": align_stage_worst,
                    "align_cell_at_stage_worst_ps": align_cell_at_stage_worst,
                    "align_net_at_stage_worst_ps": align_net_at_stage_worst,
                    "align_stage_at_stage_worst_ps": align_stage_at_stage_worst,
                    "stage_delta_center_ps": diff(align_stage_center, quiet_stage),
                    "stage_delta_worst_ps": diff(align_stage_worst, quiet_stage),
                    "net_delta_worst_ps": diff(align_net_worst, quiet_net),
                    "cell_delta_worst_ps": diff(align_cell_worst, quiet_cell),
                    "cell_delta_at_stage_worst_ps": diff(align_cell_at_stage_worst, quiet_cell),
                    "net_delta_at_stage_worst_ps": diff(align_net_at_stage_worst, quiet_net),
                    "repro_selected_pct": ratio_pct(diff(align_stage_worst, quiet_stage), pt_delta),
                    "stage_dir": str(stage_dir),
                }
            )
        except Exception as exc:  # noqa: BLE001 - keep batch alive.
            results.append(
                {
                    "stage_idx": int(stage_idx),
                    "status": "FAIL",
                    "message": str(exc),
                    "analysis_type": rec.get("analysis_type", ""),
                    "victim_net": rec.get("victim_net", ""),
                    "stage_dir": str(stage_dir),
                }
            )
            print(f"FAIL stage {stage_idx}: {exc}", file=sys.stderr)
            if not args.continue_on_error:
                raise

    args.out_csv.parent.mkdir(parents=True, exist_ok=True)
    write_results_csv(args.out_csv, results)
    write_results_rpt(args.out_rpt, results)
    print(f"Wrote {args.out_csv}")
    print(f"Wrote {args.out_rpt}")


def as_float(value: object) -> float | None:
    if value in (None, ""):
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def diff(a: float | None, b: float | None) -> float | None:
    if a is None or b is None:
        return None
    return a - b


def ratio_pct(num: float | None, den: float | None) -> float | None:
    if num is None or den is None or abs(den) < 1.0e-12:
        return None
    return 100.0 * num / den


def fmt(value: object, width: int = 9, prec: int = 2) -> str:
    if value is None:
        return " " * (width - 1) + "-"
    if isinstance(value, str):
        return value[:width].rjust(width)
    try:
        val = float(value)
    except (TypeError, ValueError):
        return str(value)[:width].rjust(width)
    if math.isnan(val):
        return " " * (width - 1) + "-"
    return f"{val:{width}.{prec}f}"


def write_results_csv(path: Path, results: list[dict[str, object]]) -> None:
    fieldnames: list[str] = []
    for row in results:
        for key in row:
            if key not in fieldnames:
                fieldnames.append(key)
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(results)


def valid_rows(results: Iterable[dict[str, object]]) -> list[dict[str, object]]:
    return [row for row in results if row.get("status") == "PASS"]


def sum_field(rows: Iterable[dict[str, object]], field: str) -> float:
    total = 0.0
    for row in rows:
        value = row.get(field)
        if value is None:
            continue
        try:
            value_f = float(value)
        except (TypeError, ValueError):
            continue
        if not math.isnan(value_f):
            total += value_f
    return total


def write_results_rpt(path: Path, results: list[dict[str, object]]) -> None:
    rows = valid_rows(results)
    fail_count = len(results) - len(rows)
    sum_pt_delta = sum_field(rows, "pt_arc_delta_selected_ps")
    sum_hsp_delta = sum_field(rows, "stage_delta_worst_ps")
    sum_hsp_center = sum_field(rows, "stage_delta_center_ps")
    ratio = ratio_pct(sum_hsp_delta, sum_pt_delta)

    with path.open("w") as f:
        f.write("Path-wide aligned-arc quiet-vs-aligned stage comparison\n")
        f.write("Method: for each path net arc, compare the same PT write_spice_deck arc deck with aligned aggressors vs quiet aggressors.\n")
        f.write("Important: the sum is a per-arc worst-style sum, not one simultaneous full-path transient waveform.\n\n")
        f.write(f"total_stages          = {len(results)}\n")
        f.write(f"pass_stages           = {len(rows)}\n")
        f.write(f"failed_stages         = {fail_count}\n")
        f.write(f"sum_PT_selected_delta = {sum_pt_delta:.3f} ps\n")
        f.write(f"sum_HSPICE_center_delta(stage) = {sum_hsp_center:.3f} ps\n")
        f.write(f"sum_HSPICE_worst_delta(stage)  = {sum_hsp_delta:.3f} ps\n")
        f.write(f"reproduction_vs_selected_PT    = {ratio:.1f} %\n\n" if ratio is not None else "\n")

        f.write(
            "Stage  Dir  Victim                  PTdel   QuietStg  Align0Stg  AlignWorst  HSPdelW  Repro%   NetOnly  Mode                    Stage arc\n"
        )
        f.write(
            "-----  ---  ----------------------  ------  --------  ---------  ----------  -------  -------  -------  ----------------------  ----------------------------------------------\n"
        )
        for row in sorted(rows, key=lambda r: int(r["stage_idx"])):
            f.write(
                f"{int(row['stage_idx']):5d}  "
                f"{str(row.get('direction', '')):>3}  "
                f"{str(row.get('victim_net', ''))[:22]:22s}  "
                f"{fmt(row.get('pt_arc_delta_selected_ps'), 6, 2)}  "
                f"{fmt(row.get('quiet_stage_ps'), 8, 2)}  "
                f"{fmt(row.get('align_stage_center_ps'), 9, 2)}  "
                f"{fmt(row.get('align_stage_worst_ps'), 10, 2)}  "
                f"{fmt(row.get('stage_delta_worst_ps'), 7, 2)}  "
                f"{fmt(row.get('repro_selected_pct'), 7, 1)}  "
                f"{fmt(row.get('net_delta_worst_ps'), 7, 2)}  "
                f"{str(row.get('stage_measure_mode', ''))[:22]:22s}  "
                f"{row.get('stage_arc', '')}\n"
            )
        failed = [row for row in results if row.get("status") != "PASS"]
        if failed:
            f.write("\nFailed or missing stages\n")
            for row in failed:
                f.write(f"stage {row.get('stage_idx')}: {row.get('status')} {row.get('message', '')}\n")


